#!/bin/bash
GOTSYNC_REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
GOTSYNC_WORKSPACE_ID="$(printf '%s' "$GOTSYNC_REPO_ROOT" | cksum | cut -d ' ' -f 1)"
GOTSYNC_CACHE_DIR="${GOTSYNC_CACHE_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/gotsync/$GOTSYNC_WORKSPACE_ID}"
export UV_PROJECT_ENVIRONMENT="$GOTSYNC_CACHE_DIR/python"
export GOTSYNC_SWIFT_SCRATCH_PATH="${GOTSYNC_SWIFT_SCRATCH_PATH:-$GOTSYNC_CACHE_DIR/swift-build}"
export PYTHONDONTWRITEBYTECODE=1
export PYTEST_ADDOPTS="${PYTEST_ADDOPTS:+$PYTEST_ADDOPTS }-p no:cacheprovider"
